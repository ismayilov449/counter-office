// Builds the walking routes of the van extraction demo (public/dev/van-demo.html) from the bots' nav grid on
// cs_mansion, so the actors walk where players can: node dev/van-demo/routes.mjs -> public/dev/van-routes.js
import fs from 'fs';
import { MAPS } from '../../shared/maps/index.js';
import { CollisionWorld } from '../../shared/collision.js';
import { buildNav, smoothPath } from '../../lib/nav.js';

const M = MAPS.cs_mansion, world = new CollisionWorld(M), nav = buildNav(M, world);
const VAN = [-41, 0, 4];
const ROUTES = {
  ct1: [[27.5, 0, -15], [-9, 0.81, -2.2]], // through the front door, into the hall
  ct2: [[25.1, 0, -13], [-12.4, 0.81, -1.4]], // to the downstairs hostage
  ct3: [[27.5, 0, -11.6], [-4.5, 0, -4.5]], // holds outside the front door
  h2out: [[-12.4, 0.81, -1.4], [25.5, 0, -3]], // CT2 leads the downstairs hostage out to the street
  ct2back: [[25.5, 0, -3], [-33, 0, -8]], // CT2 runs round to the van once it honks
  ct3up: [[-4.5, 0, -4.5], [-18, 4.27, -6]], // CT3 searches upstairs (the wrong way)
  ct3down: [[-18, 4.27, -6], [-34, 0, -2]], // and comes back down too late
  t1: [[-21.4, 4.27, -3.2], VAN], // T1 leads the first upstairs hostage to the van
  t2: [[-21.4, 4.27, 3.0], [VAN[0], 0, VAN[2] + 1.2]], // T2 the second
  t3: [[-17, 0.81, 2.5], [-11, 0.81, -1.2]], // T3 steps out to the hall
};
const out = {};
for (const [k, [a, b]] of Object.entries(ROUTES)) {
  const f = nav.nodeAt(a, 4), t = nav.nodeAt(b, 6);
  const nodes = f >= 0 && t >= 0 ? nav.path(f, t, true) : null;
  if (!nodes) throw new Error(`no route for ${k}`);
  out[k] = [a, ...smoothPath(nav, nodes, world).map(w => w.p), b].map(p => p.map(v => Math.round(v * 100) / 100));
  const len = out[k].reduce((s, p, i) => (i ? s + Math.hypot(...p.map((v, j) => v - out[k][i - 1][j])) : 0), 0);
  console.log(k.padEnd(8), out[k].length, 'points', len.toFixed(1), 'm');
}
fs.writeFileSync(new URL('../../public/dev/van-routes.js', import.meta.url),
  `// Generated by dev/van-demo/routes.mjs (the bots' nav grid on cs_mansion). Don't edit by hand.\nexport const VAN = ${JSON.stringify(VAN)};\nexport const ROUTES = ${JSON.stringify(out)};\n`);
